import { contextBridge, ipcRenderer, webUtils } from 'electron';

type R<T> = { ok: boolean; data?: T; error?: string };
/** Desembrulha {ok,data,error}: erros viram exceções no renderer. */
const call = async (ch: string, ...a: unknown[]) => {
  const r = (await ipcRenderer.invoke(ch, ...a)) as R<unknown>;
  if (!r.ok) throw new Error(r.error ?? 'erro desconhecido');
  return r.data;
};

